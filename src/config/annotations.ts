/**
 * Especificaciones de implementación Shopify por componente.
 *
 * Reglas editoriales:
 *  - "theme" significa que depende del tema elegido. Mientras `meta.themeName` sea null,
 *    la UI muestra "Compatibilidad de tema pendiente" en lugar de afirmar soporte.
 *  - No se afirma que un tema concreto soporta una función: eso se valida al seleccionar el tema.
 *  - Las capacidades nativas citadas son de plataforma (Shopify / apps de Shopify), no del tema.
 */
